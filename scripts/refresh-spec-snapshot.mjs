#!/usr/bin/env node
// Refresh spec/request-schemas.json from the AlterLab OpenAPI spec.
//
//   node scripts/refresh-spec-snapshot.mjs                 # fetch https://alterlab.io/openapi.json
//   node scripts/refresh-spec-snapshot.mjs path/to/openapi.json
//   node scripts/refresh-spec-snapshot.mjs https://example/openapi.json
//
// The snapshot holds the fully $ref-resolved request-body schemas (and query
// parameters) of every endpoint an MCP tool calls. test/schema-parity.test.mjs
// compares the tool schemas against it, so after refreshing, `npm test` shows
// exactly which tool parameters need to change.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const DEFAULT_SPEC_URL = "https://alterlab.io/openapi.json";
const OUT = resolve(dirname(fileURLToPath(import.meta.url)), "../spec/request-schemas.json");

// "METHOD path" -> snapshot key. Keep in sync with the endpoints used by src/client.ts.
export const ENDPOINTS = [
  "POST /api/v1/scrape",
  "POST /api/v1/scrape/estimate",
  "POST /api/v1/extract",
  "POST /api/v1/batch",
  "POST /api/v1/map",
  "POST /api/v1/crawl",
  "POST /api/v1/search",
  "POST /api/v1/sessions",
  "PATCH /api/v1/sessions/{session_id}",
  "POST /api/v1/sessions/{session_id}/refresh",
];

// Endpoints that take no request body but must still exist in the spec.
export const PRESENT_ONLY = [
  "GET /api/v1/billing/balance",
  "GET /api/v1/usage",
  "GET /api/v1/jobs/{job_id}",
  "GET /api/v1/sessions",
  "GET /api/v1/sessions/{session_id}",
  "DELETE /api/v1/sessions/{session_id}",
  "POST /api/v1/sessions/{session_id}/validate",
  "GET /api/v1/crawl/{crawl_id}",
  "DELETE /api/v1/crawl/{crawl_id}",
  "GET /api/v1/batch/{batch_id}",
  "GET /api/v1/beta-features",
  "GET /api/v1/beta-features/my",
  "POST /api/v1/beta-features/{slug}/enable",
  "POST /api/v1/beta-features/{slug}/disable",
];

const KEEP = new Set([
  "type", "enum", "const", "properties", "required", "items", "anyOf", "oneOf", "allOf",
  "minimum", "maximum", "minLength", "maxLength", "minItems", "maxItems", "format",
  "additionalProperties", "default",
]);

function resolveSchema(node, root, seen = []) {
  if (Array.isArray(node)) return node.map((n) => resolveSchema(n, root, seen));
  if (node === null || typeof node !== "object") return node;
  if (node.$ref) {
    const name = node.$ref.split("/").pop();
    if (seen.includes(name)) return { type: "object", "x-recursive": name };
    return resolveSchema(root.components.schemas[name], root, [...seen, name]);
  }
  const out = {};
  for (const [k, v] of Object.entries(node)) {
    if (k === "properties") {
      out.properties = {};
      for (const [pk, pv] of Object.entries(v)) out.properties[pk] = resolveSchema(pv, root, seen);
    } else if (k === "default" || k === "enum" || k === "const") {
      out[k] = v;
    } else if (KEEP.has(k)) {
      out[k] = resolveSchema(v, root, seen);
    }
  }
  return out;
}

async function loadSpec(source) {
  if (/^https?:\/\//.test(source)) {
    const res = await fetch(source);
    if (!res.ok) throw new Error(`GET ${source} -> ${res.status}`);
    return res.json();
  }
  return JSON.parse(readFileSync(source, "utf8"));
}

const source = process.argv[2] ?? DEFAULT_SPEC_URL;
const spec = await loadSpec(source);
const snapshot = {
  _meta: {
    source: /^https?:\/\//.test(source) ? source : "local file",
    openapi_info_version: spec.info?.version ?? null,
    note: "Generated by scripts/refresh-spec-snapshot.mjs. Do not edit by hand.",
  },
  endpoints: {},
  present_only: [],
};

for (const key of ENDPOINTS) {
  const [method, path] = key.split(" ");
  const op = spec.paths?.[path]?.[method.toLowerCase()];
  if (!op) throw new Error(`Spec has no ${key}`);
  const schema = op.requestBody?.content?.["application/json"]?.schema;
  if (!schema) throw new Error(`${key} has no JSON request body`);
  snapshot.endpoints[key] = resolveSchema(schema, spec);
}
for (const key of PRESENT_ONLY) {
  const [method, path] = key.split(" ");
  if (!spec.paths?.[path]?.[method.toLowerCase()]) throw new Error(`Spec has no ${key}`);
  snapshot.present_only.push(key);
}

writeFileSync(OUT, JSON.stringify(snapshot, null, 2) + "\n");
console.log(`Wrote ${OUT} (${ENDPOINTS.length} request schemas, ${PRESENT_ONLY.length} presence checks, spec ${spec.info?.version})`);
